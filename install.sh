#!/bin/sh
# Install or update the Start12 widget for the current user, then reload Plasma.
set -e
cd "$(dirname "$0")"
# Developer checks run only when node is installed.
if command -v node >/dev/null 2>&1; then node tests/test_tiles.js; fi
# Spanish translation (Plasma looks in contents/locale/<lang>/LC_MESSAGES/plasma_applet_<id>.mo);
# the compiled .mo is shipped, so gettext is only needed to rebuild it.
if command -v msgfmt >/dev/null 2>&1; then
    mkdir -p package/contents/locale/es/LC_MESSAGES
    msgfmt --check -o package/contents/locale/es/LC_MESSAGES/plasma_applet_org.start12.menu.mo po/es.po
fi
if kpackagetool6 -t Plasma/Applet -l | grep -qx org.start12.menu; then
    kpackagetool6 -t Plasma/Applet -u package
else
    kpackagetool6 -t Plasma/Applet -i package
fi
install -Dm755 extras/start12-settings "$HOME/.local/bin/start12-settings"
install -Dm644 extras/start12-settings.desktop "$HOME/.local/share/applications/start12-settings.desktop"
# Plasma Styles for the XP taskbar (applied by the widget when the XP menu style is used).
# Custom colours are generated by the widget itself (start12-xp-<sub>-custom-<hex>).
python3 package/contents/ui/code/xptheme.py "$HOME/.local/share/plasma/desktoptheme"
# Window decorations for the same schemes (T26a, applied when the windowTheme key is on).
python3 package/contents/ui/code/xptheme.py --deco "$HOME/.local/share/aurorae/themes"
# Colour schemes for the same schemes (T26b, same windowTheme key).
python3 package/contents/ui/code/xptheme.py --scheme "$HOME/.local/share/color-schemes"
if [ "$1" = "--restart" ]; then
    systemctl --user restart plasma-plasmashell.service
fi
